#!/usr/bin/env python3
"""Add an idempotent "Try it on medux.io" block to each API example.

The block lists the Playground and Workshop pages that use the endpoint and links
the matching MCP examples. The page-to-example mapping is generated by
../medux-mcp-examples/scripts/link_workshop_pages.py (docs/workshop-pages.json), so
run that script first. Re-run this one after the examples are regenerated.

    python3 scripts/link_workshop_pages.py
"""
import json
import os
import re

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
MCP_ROOT = os.path.normpath(os.path.join(ROOT, "..", "medux-mcp-examples"))
SITE = "https://medux.io"
MCP_GH = "https://github.com/MeduxIO/medux-mcp-examples/tree/main"
BEGIN, END = "<!-- medux-pages:start -->", "<!-- medux-pages:end -->"


def main():
    pages = json.load(open(f"{MCP_ROOT}/docs/workshop-pages.json"))["pages"]
    by_api = {}
    for pg, e in pages.items():
        by_api.setdefault(e["api"], []).append((pg, e))
    for api, items in by_api.items():
        readme = f"{ROOT}/{api}/README.md"
        if not os.path.exists(readme):
            raise SystemExit(f"missing {readme}")
        first = items[0][1]
        rows = []
        for pg, _ in sorted(items):
            kind = "Playground" if pg.startswith("/playground") else "Workshop"
            rows.append(f"| {kind} | [medux.io{pg}]({SITE}{pg.replace('/*', '')}) |")
        tools = sorted({e["tool"] for _, e in items})
        block = "\n".join([
            BEGIN, "## Try it on medux.io", "",
            "| Type | Page |", "| --- | --- |", *dict.fromkeys(rows), "",
            f"- MCP tool: `{'`, `'.join(tools)}`",
            f"- Claude MCP example: [{first['claude']}]({MCP_GH}/{first['claude']})",
            f"- Codex MCP example: [{first['codex']}]({MCP_GH}/{first['codex']})",
            f"- All pages: [Playground and Workshop pages](https://github.com/MeduxIO/medux-mcp-examples/blob/main/docs/workshop-pages.md)",
            END, ""])
        text = open(readme).read()
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", "", text, flags=re.S)
        m = re.search(r"^## Source of truth", text, flags=re.M)
        text = (text[:m.start()] + block + "\n" + text[m.start():]) if m else (text.rstrip("\n") + "\n\n" + block)
        open(readme, "w").write(text)
    print(f"updated {len(by_api)} API examples")


if __name__ == "__main__":
    main()
